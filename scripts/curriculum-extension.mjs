export function makeAdvancedTopics(language) {
  return advancedTracks[language].flatMap((track) =>
    advancedAngles.map((angle) => `${track}: ${angle}`),
  );
}

export function makeProjectTopics(language) {
  const formats = projectFormatsByLanguage[language] ?? projectFormats;
  return projectDomains[language].flatMap((domain) =>
    formats.map((format) => `프로젝트: ${domain} ${format}`),
  );
}

for (const language of Object.keys(advancedTracks)) {
  if (
    makeAdvancedTopics(language).length !== 60 ||
    makeProjectTopics(language).length !== 60
  ) {
    throw new Error(
      `${language} 확장 과정은 심화 60개와 프로젝트 60개여야 합니다.`,
    );
  }
}
